#!/usr/bin/env python3
"""Generate crates/diting/js/method_ladders.js: WebIDL required-argument checks for the methods the engine lacks them on.

Chrome rejects a call with fewer arguments than the method's required count with
`TypeError: Failed to execute 'm' on 'Interface': N argument(s) required, but only K present.` before touching the receiver
(promise-returning operations REJECT instead of throwing). Two truth files merge into one table:
  ladders-truth-145.json     every no-arg CONSTRUCTIBLE interface (ladders-probe.js, 刀80)
  ladders-inst-truth-145.json the INSTANCE-REQUIRING interfaces (ladders-inst-probe.js, 刀95):
    elements/document/window/storage/observers/2d-canvas/etc — methods live on a real
    instance; only fn.length>=1 prototype methods are probed, so the argc TypeError fires
    before any side effect (the hang risk that killed the wide probe does not apply).
    Chrome placement quirk: Window/Location methods are OWN on the instance (their
    prototypes carry only constructor), so the generated wrapper installs on the object
    itself for those two. The generated file wraps exactly the differing methods in a
    prototype-less method-shorthand wrapper that performs the check and delegates through
    Reflect.apply. (A blanket wrap of every Chrome length>0 method was tried and rejected:
    it fought brand-first ordering, error-object shapes and carefully hand-built ladders.)
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
T = json.load(open(os.path.join(ROOT, 'tools/webplatform/chrome/shape-audit-truth-145.json')))
out_p = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'crates/diting/js/method_ladders.js')
SYNC, PROM = {}, {}
for _f in ('ladders-truth-145.json', 'ladders-inst-truth-145.json'):
    _L = json.load(open(os.path.join(ROOT, 'tools/webplatform/chrome', _f)))
    for _k, _v in _L['sync'].items(): SYNC.setdefault(_k, {}).update(_v)
    for _k, _v in _L['promise'].items(): PROM.setdefault(_k, {}).update(_v)
body = '''// GENERATED by tools/webplatform/gen/gen_method_ladders.py from chrome/ladders-truth-145.json + ladders-inst-truth-145.json - do not edit.
// WebIDL required-argument ladders (M4 刀80) for the methods whose no-argument behaviour differed from Chrome: SYNC throws
// Chrome's TypeError, PROMISE rejects with it. Wrappers are method-shorthand functions (no `prototype`, not constructible),
// keep the original descriptor flags and delegate through Reflect.apply.
(function () {
  const G = globalThis;
  const mark = G.__diting_markNative || ((f) => f);
  // (刀95) Chrome placement quirk: Window/Location methods are OWN on the instance
  // (their prototypes carry only constructor) — wrap in place on the object itself.
  const OWNOF = { Window: G, Location: G.location };
  const SYNC = %s;
  const PROMISE = %s;
  const wrap = (iface, name, N, isPromise) => {
    const C = G[iface];
    const obj = OWNOF[iface] !== undefined ? OWNOF[iface] : (typeof C === 'function' ? C.prototype : null);
    const d = obj && Object.getOwnPropertyDescriptor(obj, name);
    if (!d || typeof d.value !== 'function' || !d.configurable) return;
    const orig = d.value;
    const w = { [name](...a) {
      if (a.length < N) {
        const e = new TypeError("Failed to execute '" + name + "' on '" + iface + "': " + N + ' argument' + (N > 1 ? 's' : '') + ' required, but only ' + a.length + ' present.');
        if (isPromise) return Promise.reject(e);
        throw e;
      }
      return Reflect.apply(orig, this, a);
    } }[name];
    Object.defineProperty(w, 'length', { value: d.value.length, configurable: true });
    mark(w);
    Object.defineProperty(obj, name, { value: w, writable: d.writable, enumerable: d.enumerable, configurable: true });
  };
  for (const iface of Object.keys(SYNC)) for (const m of Object.keys(SYNC[iface])) wrap(iface, m, SYNC[iface][m], false);
  for (const iface of Object.keys(PROMISE)) for (const m of Object.keys(PROMISE[iface])) wrap(iface, m, PROMISE[iface][m], true);
})();
''' % (json.dumps(SYNC, separators=(',', ':'), sort_keys=True), json.dumps(PROM, separators=(',', ':'), sort_keys=True))
open(out_p, 'w').write(body)
print('sync', sum(len(v) for v in SYNC.values()), 'promise', sum(len(v) for v in PROM.values()), 'bytes', len(body))
