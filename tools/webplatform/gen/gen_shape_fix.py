#!/usr/bin/env python3
"""Generate crates/diting/js/shape_fix.js from the whole-surface shape audit.

  gen_shape_fix.py <engine.json> [out.js]

Compares an engine capture (probe_run.py engine shape-audit-probe.js) with chrome/shape-audit-truth-145.json and
emits a data table of the descriptor-level facts the engine gets wrong on members both sides have:
  - function `length` (methods and constructors),
  - the e/c/w attribute flags of methods, accessors, constants (class methods are non-enumerable in JS,
    WebIDL operations/attributes are enumerable).
ro/rw (setter presence) differences are NOT touched: engine code may write through them.
NOTE: capture the engine WITHOUT shape_fix.js applied (comment it out of build.rs) when regenerating, otherwise the
table comes out empty. Output is applied last (build.rs) by shape_fix.js itself.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(HERE, '../chrome/shape-audit-truth-145.json')))
E = json.load(open(sys.argv[1]))
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '../../../crates/diting/js/shape_fix.js')

def parse(k):
    if k is None or k == 'err': return None
    parts = k.split(':')
    if parts[0] in ('ro', 'rw'): return ('acc', parts[0], None, parts[1])
    if parts[0] == 'function': return ('fn', None, int(parts[1]), parts[2])
    return ('data', parts[0], None, parts[1])

def entries(ck, ek, order):
    res = []
    for m in order:
        c, e = parse(ck.get(m)), parse(ek.get(m))
        if c is None or e is None or c[0] != e[0]: continue
        if c[0] == 'acc' and c[1] != e[1]: continue
        if c[0] == 'data' and c[1] != e[1]: continue
        ln = c[2] if (c[0] == 'fn' and c[2] != e[2]) else -1
        fl = c[3] if c[3] != e[3] else ''
        if ln < 0 and not fl: continue
        res.append([m, ln, fl])
    return res

P, S, L = {}, {}, {}
for n, c in T.items():
    e = E.get(n)
    if not e: continue
    pe = entries(c['kinds'], e['kinds'], [m for m in c['order'] if m in e['order'] and m != 'constructor'])
    if pe: P[n] = pe
    se = entries(c['skinds'], e['skinds'], [m for m in c['statics'] if m in e['statics']])
    if se: S[n] = se
    if c['len'] != e['len']: L[n] = c['len']
body = '// GENERATED by tools/webplatform/gen/gen_shape_fix.py from chrome/shape-audit-truth-145.json - do not edit.\n'
body += '// Descriptor-level conformance (function length, e/c/w flags, constructor length) for members both Chrome and\n'
body += '// the engine have. Applied LAST (build.rs) so every earlier script\'s classes are final. [member, length|-1, flags|""]\n'
body += '(function () {\n  const PROTO = %s;\n  const STAT = %s;\n  const CTOR = %s;\n' % (json.dumps(P, separators=(',', ':')), json.dumps(S, separators=(',', ':')), json.dumps(L, separators=(',', ':')))
body += '''  const apply = (obj, ent) => {
    for (const [m, len, fl] of ent) {
      try {
        const d = Object.getOwnPropertyDescriptor(obj, m);
        if (!d) continue;
        if (len >= 0 && typeof d.value === 'function') Object.defineProperty(d.value, 'length', { value: len, configurable: true });
        if (fl) {
          const nd = { enumerable: fl[0] === 'e', configurable: fl[1] === 'c' };
          if ('value' in d) nd.writable = fl[2] === 'w';
          Object.defineProperty(obj, m, nd);
        }
      } catch (e) {}
    }
  };
  for (const n of Object.keys(PROTO)) { const C = globalThis[n]; if (typeof C === 'function' && C.prototype) apply(C.prototype, PROTO[n]); }
  for (const n of Object.keys(STAT)) { const C = globalThis[n]; if (typeof C === 'function') apply(C, STAT[n]); }
  for (const n of Object.keys(CTOR)) {
    const C = globalThis[n];
    try { if (typeof C === 'function') Object.defineProperty(C, 'length', { value: CTOR[n], configurable: true }); } catch (e) {}
  }
})();
'''
open(out, 'w').write(body)
print('proto', sum(len(v) for v in P.values()), 'static', sum(len(v) for v in S.values()), 'ctor', len(L), 'bytes', len(body))
