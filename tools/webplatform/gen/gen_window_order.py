#!/usr/bin/env python3
"""Generate crates/diting/js/window_order.js: Chrome 145's Object.getOwnPropertyNames(window) order.

  gen_window_order.py <instance-audit-chrome.json> [out.js]

Fingerprinting collectors hash the ORDERED own-name list of window (Radar's windowFeatures). The engine builds globals in script
order, so the order differs almost everywhere (1151 of 1212 positions). At the very end the generated list is applied: every
configurable global that Chrome also has is deleted and re-defined in Chrome's order (engine-only configurable names go first, so
the Chrome-ordered run stays contiguous and the hidden internals never interleave); non-configurable globals cannot move.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
C = json.load(open(sys.argv[1]))
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '../../../crates/diting/js/window_order.js')
names = C['Window']['names']
body = '// GENERATED by tools/webplatform/gen/gen_window_order.py from chrome/instance-audit (Chrome 145 window own names) - do not edit.\n'
body += '(function () {\n  const ORDER = %s;\n  const run = function () {\n' % json.dumps(names, separators=(',', ':'))
body += '''  // capture every primitive first: the loop deletes `Object` / `Reflect` / `Set` themselves from the global
  const g = globalThis, gopd = Object.getOwnPropertyDescriptor, def = Object.defineProperty, del = Reflect.deleteProperty;
  const hasOwn = Object.prototype.hasOwnProperty, gopn = Object.getOwnPropertyNames;
  // engine state the Rust host / parser assign at run time (globalThis.x = ...): declared hidden up front so the later plain
  // assignments keep the non-enumerable attributes (an assignment to an absent name would mint an enumerable property)
  for (const n of ["__diting_objects", "__diting_oid", "__diting_hw", "__diting_mem", "__diting_hw_plat", "__diting_gopn_patched", "__diting_ua",
    "__diting_lang", "__documentReadyState__", "__parserScriptOrder", "__parserScriptIdx", "__parserScriptCeiling", "__currentScriptNid", "__diting_click_target"]) {
    if (!hasOwn.call(g, n)) def(g, n, { value: undefined, writable: true, enumerable: false, configurable: true });
  }
  const want = new Set(ORDER);
  const have = gopn(g);
  // engine-only configurable names first (they are hidden from enumeration anyway), then Chrome's order
  const seq = have.filter((n) => !want.has(n)).concat(ORDER.filter((n) => hasOwn.call(g, n)));
  for (const n of seq) {
    const d = gopd(g, n);
    if (!d || !d.configurable) continue;
    // a name Chrome's window does not have is engine-internal: it must not show up in for-in / JSON / spread either
    if (d.enumerable && !want.has(n)) d.enumerable = false;
    del(g, n);
    def(g, n, d);
  }
  // Chrome's window.chrome is NON-configurable (only Infinity/NaN/undefined/window/document/location/top/chrome are); now
  // that it sits at its final position, freeze its configurability.
  { const d = gopd(g, 'chrome'); if (d && d.configurable) def(g, 'chrome', Object.assign({}, d, { configurable: false })); }
  };
  // once at snapshot time, and again at the end of every page init (window_faces / __diting_init re-install some window
  // accessors per page, which appends them at the END of the key order)
  run();
  Object.defineProperty(globalThis, '__diting_reorder_window', { value: run, writable: true, enumerable: false, configurable: true });
})();
'''
open(out, 'w').write(body)
print(len(names), 'names', len(body), 'bytes')
