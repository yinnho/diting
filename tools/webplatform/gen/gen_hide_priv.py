#!/usr/bin/env python3
"""Generate crates/diting/js/hide_priv.js: hidden-slot accessors for the engine's `_x` private fields.

  gen_hide_priv.py <enum-engine.json> [out.js]

The engine's classes keep private state as plain own properties (`this._nid = nid`, `this._bytes = ...`), which for-in, JSON.stringify,
Object.assign and spread all see (Chrome's instances have none). Rewriting every constructor is a long tail, so instead each such
name gets an accessor pair on the nearest COMMON prototype of the objects that carry it: the setter turns the first assignment on an
instance into a NON-ENUMERABLE own data property (`defineProperty(this, n, {value, writable, configurable})`); from then on reads and
writes hit that own property directly. The getter answers undefined, exactly what an absent field answered. Input: an engine capture
of chrome/enum-probe.js (its `#chains` key holds each object's prototype-chain constructor names). Names that start with `_` only.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
E = json.load(open(sys.argv[1]))
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '../../../crates/diting/js/hide_priv.js')
chains = E.get('#chains', {})
users = {}  # field -> list of chains
for n, ks in E.items():
    if n.startswith('#') or not isinstance(ks, list) or n not in chains: continue
    for k in ks:
        if k.startswith('_'): users.setdefault(k, []).append(chains[n])
# special: window/globalThis are handled elsewhere
data = {}
for f, cs in sorted(users.items()):
    common = None
    for c in cs:
        c = [x for x in c if x not in ('Object', '?')]
        s = c if common is None else [x for x in common if x in c]
        common = s
    if common:
        owner = common[0]
        data.setdefault(owner, []).append(f)
    else:  # no common non-Object ancestor: each class gets it
        for c in cs:
            c = [x for x in c if x not in ('Object', '?')]
            if c: data.setdefault(c[0], []).append(f)
# merge with the DATA already shipped: a capture taken WITH hide_priv applied no longer shows the fields it hides
if os.path.exists(out):
    import re
    m = re.search(r'const DATA = (\{.*?\});\n', open(out).read())
    if m:
        for k, v in json.loads(m.group(1)).items(): data.setdefault(k, []).extend(v)
extra_path = os.path.join(HERE, 'hide_priv_extra.json')
if os.path.exists(extra_path):
    for k, v in json.load(open(extra_path)).items():
        if not k.startswith('_'): data.setdefault(k, []).extend(v)
data = {k: sorted(set(v)) for k, v in sorted(data.items())}
body = '// GENERATED by tools/webplatform/gen/gen_hide_priv.py - do not edit. See the generator header for the contract.\n'
body += '(function () {\n  const DATA = %s;\n' % json.dumps(data, separators=(',', ':'))
body += '''  const mark = globalThis.__diting_markNative || ((f) => f);
  const hasOwn = Object.prototype.hasOwnProperty, def = Object.defineProperty;
  for (const cn of Object.keys(DATA)) {
    const C = globalThis[cn];
    if (typeof C !== 'function' || !C.prototype) continue;
    const P = C.prototype;
    for (const n of DATA[cn]) {
      if (hasOwn.call(P, n)) continue;
      try {
        const get = mark({ ['get ' + n]: function () { return undefined; } }['get ' + n]);
        const set = mark({ ['set ' + n]: function (v) { def(this, n, { value: v, writable: true, enumerable: false, configurable: true }); } }['set ' + n]);
        def(P, n, { get, set, enumerable: false, configurable: true });
      } catch (e) {}
    }
  }
})();
'''
open(out, 'w').write(body)
print({k: len(v) for k, v in data.items()}, os.path.getsize(out), 'bytes')
