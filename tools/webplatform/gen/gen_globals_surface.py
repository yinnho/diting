#!/usr/bin/env python3
# Generate crates/diting/js/global_surface.js from Chrome-155 truth captures.
# Sources (tools/webplatform/chrome/): fp-winkeys-diff.json (missing names — a
# FROZEN historical input: the names the engine lacked when this was first
# generated; it cannot be recomputed from today's engine), fp-chrome-shapes.json (typeof/
# length/ctor message/descriptor flags), fp-chrome-objflags.json (object/bool/on*
# accessor detail). Regenerate after re-shooting any of those.
import json
import os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
CHROME = os.path.join(ROOT, "tools", "webplatform", "chrome")
# usage: <this script> [OUT_DIR]   (default: crates/diting/js — the checked-in artifact)
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "crates", "diting", "js")

shapes = json.load(open(os.path.join(CHROME, "fp-chrome-shapes.json")))
objflags = json.load(open(os.path.join(CHROME, "fp-chrome-objflags.json")))
chrome_keys = json.load(open(os.path.join(CHROME, "fp-chrome-winkeys-example.json")))
et_truth = json.load(open(os.path.join(CHROME, "eventtarget-chain-truth-145.json")))

def kind(name, v):
    t = v["t"]
    if t == "function":
        c = v.get("ctor")
        if c == "ok":
            return "ok"
        if c and "not a constructor" in c:
            return "method"
        return "throw"
    return t  # object | boolean | undefined

groups = {"throw": [], "ok": [], "method": [], "object": [], "boolean": [], "undefined": []}
for name in json.load(open(os.path.join(CHROME, "fp-winkeys-diff.json")))["missing"]:
    if len(name) <= 1:
        continue  # 'B'/'p' page artifacts
    v = shapes[name]
    groups[kind(name, v)].append(name)
for k in groups:
    groups[k].sort()

# chrome's exact window on* surface (for the bootstrap list swap)
on_all = sorted(n for n in chrome_keys if n.startswith("on"))
print("chrome on* on window:", len(on_all))

js = []
js.append("""// Global surface parity (300015 P2): the window own-prop face Chrome 155
// exposes on an https page that this engine lacked (701 names) plus the
// relocation of faces Chrome keeps off the window object. GENERATED by
// tools/webplatform/gen/gen_globals_surface.py from CDP captures of real Chrome
// (tools/webplatform/chrome/: fp-chrome-winkeys-example / fp-chrome-shapes /
// fp-chrome-objflags / fp-winkeys-diff / eventtarget-chain-truth-145) — regenerate,
// don't hand-tune the tables. Runs after every other module and before
// interface_sweep.js, so the sweeps (non-enum flip, native marks,
// toStringTag brands, name sweep, iframe frame-globals snapshot) all
// process whatever lands here.
(function () {
'use strict';
const SKIP = (n) => { try { return n in globalThis; } catch (e) { return true; } };

// ---- relocation: Chrome keeps these OFF the window object (they resolve
// via Window.prototype / EventTarget.prototype). The engine installed them
// as own props; move them up one proto layer so getOwnPropertyNames(window)
// matches Chrome while every existing call site keeps resolving.
(function relocate() {
  try {
    const P1 = Object.getPrototypeOf(globalThis);
    ['addEventListener', 'removeEventListener', 'dispatchEvent'].forEach((k) => {
      const d = Object.getOwnPropertyDescriptor(globalThis, k);
      if (!d || typeof d.value !== 'function') return;
      delete globalThis[k];
      try {
        Object.defineProperty(P1, k, { value: d.value, writable: true, enumerable: true, configurable: true });
      } catch (e) {}
    });
    // self.constructor === Window must survive the own-prop delete (Ember
    // gate, upstream 9dfc67a): Chrome keeps `constructor` on Window.prototype,
    // so point the proto layer's slot at the real Window class.
    if (!SKIP('constructor')) {
      try { Object.defineProperty(P1, 'constructor', { value: globalThis.Window, writable: true, configurable: true }); } catch (e) {}
    } else {
      try { delete globalThis.constructor; } catch (e) {}
      try { Object.defineProperty(P1, 'constructor', { value: globalThis.Window, writable: true, configurable: true }); } catch (e) {}
    }
    // iframe windows get the trio through their own proto layer, not as
    // copied own props (Chrome iframes don't own them either).
    try {
      // _IframeWindow is a top-level class binding — lexical, not a
      // globalThis own prop — so it must be read as a bare identifier.
      const IP = (typeof _IframeWindow === 'function') && _IframeWindow.prototype;
      if (IP && typeof IP.addEventListener !== 'function' && P1) {
        ['addEventListener', 'removeEventListener', 'dispatchEvent'].forEach((k) => {
          const fn = Object.getOwnPropertyDescriptor(P1, k);
          if (fn && fn.value) Object.defineProperty(IP, k, { value: fn.value, writable: true, enumerable: true, configurable: true });
        });
      }
    } catch (e) {}
  } catch (e) {}
})();
""")

js.append("""
// ---- interface factories
// Inert constructor stubs (THROW / OK lists below) register here so tooling (shape audit, stub_members.js generation)
// can tell them from real classes whose instances carry their members as own properties.
Object.defineProperty(globalThis, '__diting_stubs', { value: new WeakSet(), writable: true, enumerable: false, configurable: true });
function mkThrow(name, len, msg) {
  const C = function () { throw new TypeError(msg); };
  try { Object.defineProperty(C, 'name', { value: name, configurable: true }); } catch (e) {}
  try { Object.defineProperty(C, 'length', { value: len, configurable: true }); } catch (e) {}
  globalThis.__diting_stubs.add(C);
  return C;
}
function mkOk(name, len) {
  const C = function () { return Object.create(C.prototype); };
  try { Object.defineProperty(C, 'name', { value: name, configurable: true }); } catch (e) {}
  try { Object.defineProperty(C, 'length', { value: len, configurable: true }); } catch (e) {}
  globalThis.__diting_stubs.add(C);
  return C;
}
function mkMethod(name, len) {
  // computed method shorthand: no [[Construct]], `new X()` throws
  // "X is not a constructor" exactly like Chrome's window methods.
  const C = { [name]() {} }[name];
  if (len) { try { Object.defineProperty(C, 'length', { value: len, configurable: true }); } catch (e) {} }
  return C;
}
function tagged(tag) {
  const o = {};
  try { Object.defineProperty(o, Symbol.toStringTag, { value: tag, configurable: true }); } catch (e) {}
  return o;
}
const MARK = (f) => { try { if (typeof _markNative === 'function') _markNative(f); } catch (e) {} };
""")

# ctor-throw table
rows = []
for n in groups["throw"]:
    m = shapes[n].get("m") or "Illegal constructor"
    # (M4 刀78) Chrome's message has no trailing period
    m = m.rstrip(".") if "Illegal constructor" in m else m
    rows.append("[%s,%d,%s]" % (json.dumps(n), shapes[n].get("ln") or 0, json.dumps(m)))
js.append("""
// ---- interfaces whose constructor throws (Chrome's own message verbatim —
// the message set is per-name, down to the trailing-period inconsistency)
const THROW = [%s];
for (const [name, len, msg] of THROW) {
  if (SKIP(name)) continue;
  const C = mkThrow(name, len, msg);
  Object.defineProperty(globalThis, name, { value: C, writable: true, enumerable: false, configurable: true });
}
""" % ",\n  ".join(rows))

rows = [("[%s,%d]" % (json.dumps(n), shapes[n].get("ln") or 0)) for n in groups["ok"]]
js.append("""
// ---- constructible interfaces: `new X()` returns a branded instance
const OK = [%s];
for (const [name, len] of OK) {
  if (SKIP(name)) continue;
  const C = mkOk(name, len);
  Object.defineProperty(globalThis, name, { value: C, writable: true, enumerable: false, configurable: true });
}
""" % ",\n  ".join(rows))

# ---- EventTarget family chains (M4 knife 3): DATA from
# eventtarget-chain-truth-145.json (147 Chrome chains). Every parent must
# itself be a chain table entry or EventTarget; [LegacyAlias] names (truth
# level-0 name differs) are the SAME interface object in Chrome, so they
# alias instead of getting a separate stub (drop them from the ok group).
etc = et_truth["chains"]
et_alias, et_chain = {}, []
for n in sorted(etc):
    ch = etc[n]
    assert ch and ch[-1] == "Object", n
    if n == "EventTarget":
        continue
    if ch[0] != n:
        assert ch[0] in etc and etc[ch[0]] == ch, "alias %s -> %s not a chain twin" % (n, ch[0])
        et_alias[n] = ch[0]
        continue
    parent = ch[1]
    assert parent == "EventTarget" or (parent in etc and etc[parent][0] == parent), \
        "ET chain parent %r of %s is not a chained interface" % (parent, n)
    if parent != "Object":
        et_chain.append((n, parent))
for a in et_alias:
    for k in ("ok", "throw"):
        if a in groups[k]:
            groups[k].remove(a)
# singleton prototype links: plain-object singletons whose Chrome truth is
# [true, true, true] (proto-linked, instanceof own class, instanceof ET).
# 'matchMedia' is a function, not an object — the runtime object guard
# skips it; its instances fix up through the chain table instead.
et_single = []
for k, v in sorted(et_truth.items()):
    if not k.startswith("sin.") or v != [True, True, True]:
        continue
    path = k[4:]
    cls = et_truth.get("sincls", {}).get(path)
    assert cls, "singleton %s has no sincls entry" % path
    et_single.append((path, cls))

rows = [("[%s,%d]" % (json.dumps(n), shapes[n].get("ln") or 0)) for n in groups["method"]]
js.append("""
// ---- window methods (non-constructible): moveTo/find/file pickers/…
const METHODS = [%s];
for (const [name, len] of METHODS) {
  if (SKIP(name)) continue;
  const C = mkMethod(name, len);
  MARK(C);
  Object.defineProperty(globalThis, name, { value: C, writable: true, enumerable: true, configurable: true });
}
""" % ",\n  ".join(rows))

# objects: data-prop const tables vs accessor singletons. on* names land here
# too (typeof null-value accessor === "object") — they belong to the bootstrap
# _WINDOW_EVENT_NAMES accessor install, not to this module; SKIP would save us
# at runtime, but keep the table honest.
on_set = set(on_all)
data_objs, acc_objs = [], []
for n in groups["object"]:
    if n.startswith("on"):
        assert n in on_set, n  # covered by the chrome-exact window handler set
        continue
    f = objflags.get(n) or {}
    (data_objs if not f.get("g") else acc_objs).append(n)
rows = [json.dumps(n) for n in data_objs]
js.append("""
// ---- non-enumerable data objects (WebGPU flag-usage tables; constant
// values not reproduced yet — enumeration parity is the measured face)
const CONST_TABLES = [%s];
for (const name of CONST_TABLES) {
  if (SKIP(name)) continue;
  Object.defineProperty(globalThis, name, { value: tagged(name), writable: true, enumerable: false, configurable: true });
}
""" % ",\n  ".join(rows))

rows = []
for n in acc_objs:
    tag = (shapes[n].get("ts") or "").strip() or ("[object %s]" % n)
    rows.append("[%s,%s]" % (json.dumps(n), json.dumps(tag)))
js.append("""
// ---- enumerable getter singletons: bars/navigation/trustedTypes/…
const OBJ_GETTERS = [%s];
for (const [name, tag] of OBJ_GETTERS) {
  if (SKIP(name)) continue;
  const tag2 = tag === '[object Navigator]' ? null : tag;
  const single = name === 'clientInformation' ? null : tagged(tag2 ? tag2.slice(8, -1) || name : name);
  Object.defineProperty(globalThis, name, {
    get() { return name === 'clientInformation' ? globalThis.navigator : single; },
    enumerable: true, configurable: true,
  });
}
""" % ",\n  ".join(rows))

_AUDIT = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../chrome/shape-audit-truth-145.json")))
_ET_NAMES = set(n for n, _ in et_chain)
_AUDIT_SKIP = {"SVGElement", "SVGClipPathElement", "SVGSymbolElement", "SVGFEDropShadowElement", "PerformanceNavigationTiming",
               "PerformanceResourceTiming", "PerformanceMark", "PerformanceMeasure", "PerformancePaintTiming", "PerformanceServerTiming"}
audit_chain = [(n, v["proto"]) for n, v in sorted(_AUDIT.items())
               if v["proto"] not in ("Object", "null", "?") and n not in _ET_NAMES and n not in _AUDIT_SKIP and v["proto"] != n]

js.append("""
// ---- scalar faces
if (!SKIP('credentialless')) Object.defineProperty(globalThis, 'credentialless', { get() { return false; }, enumerable: true, configurable: true });
if (!SKIP('originAgentCluster')) Object.defineProperty(globalThis, 'originAgentCluster', { get() { return true; }, enumerable: true, configurable: true });
if (!SKIP('offscreenBuffering')) Object.defineProperty(globalThis, 'offscreenBuffering', { get() { return true; }, set() {}, enumerable: false, configurable: true });
if (!SKIP('event')) Object.defineProperty(globalThis, 'event', { get() { return undefined; }, set() {}, enumerable: true, configurable: true });

// ---- EventTarget family chains (M4 knife 3): Chrome truth pins each
// interface's prototype parent (tools/webplatform/chrome/
// eventtarget-chain-truth-145.json). The stubs above and the real classes
// from earlier scripts default to Object.prototype; one setPrototypeOf per
// name repairs the chain so the trio/when resolve through the NATIVE
// EventTarget core — including the MSE pair, whose private intermediate
// falls out of the chain (media_source.js now extends EventTarget
// directly). Runs LAST in this file so the OBJ_GETTERS singletons exist.
const ET_CHAIN = [%s];
for (const [name, parent] of ET_CHAIN) {
  try {
    const C = globalThis[name], P = globalThis[parent];
    if (typeof C === 'function' && C.prototype && typeof P === 'function' && P.prototype) {
      Object.setPrototypeOf(C.prototype, P.prototype);
    }
  } catch (e) {}
}
// Remaining prototype-parent repairs, generated from the whole-surface shape audit (chrome/shape-audit-truth-145.json): every
// interface whose Chrome 145 parent is not Object and not already handled above. Only the prototype chain is repaired here (the
// constructors' own [[Prototype]] is a separate step). Left out on purpose: the real Performance* classes wire themselves in
// performance.js, and the SVGElement family (the engine's SVGElement extends HTMLElement; re-parenting it to Element would drop
// the HTMLElement behaviour SVG elements lean on).
const AUDIT_CHAIN = [%s];
for (const [name, parent] of AUDIT_CHAIN) {
  try {
    const C = globalThis[name], P = globalThis[parent];
    if (typeof C === 'function' && C.prototype && typeof P === 'function' && P.prototype) {
      Object.setPrototypeOf(C.prototype, P.prototype);
    }
  } catch (e) {}
}
// [LegacyAlias] names are the SAME interface object in Chrome, not separate
// stubs: webkitMediaStream === MediaSource-family twins of real classes.
const ET_ALIAS = [%s];
for (const [alias, of] of ET_ALIAS) {
  try {
    const C = globalThis[of];
    if (typeof C === 'function') Object.defineProperty(globalThis, alias, { value: C, writable: true, enumerable: false, configurable: true });
  } catch (e) {}
}
// singletons the engine minted as plain objects get their prototype link
// here (Chrome: performance instanceof Performance/EventTarget === true).
const ET_SINGLETON = [%s];
for (const [path, cls] of ET_SINGLETON) {
  try {
    let o = globalThis;
    for (const k of path.split('.')) o = o == null ? o : o[k];
    const C = globalThis[cls];
    if (o && typeof o === 'object' && typeof C === 'function' && C.prototype) Object.setPrototypeOf(o, C.prototype);
  } catch (e) {}
}
})();
""" % (",\n  ".join("[%s,%s]" % (json.dumps(n), json.dumps(p)) for n, p in et_chain),
       ",\n  ".join("[%s,%s]" % (json.dumps(n), json.dumps(p)) for n, p in audit_chain),
       ",\n  ".join("[%s,%s]" % (json.dumps(a), json.dumps(b)) for a, b in sorted(et_alias.items())),
       ",\n  ".join("[%s,%s]" % (json.dumps(a), json.dumps(b)) for a, b in et_single)))

open(os.path.join(OUT, "global_surface.js"), "w").write("".join(js))
print("wrote crates/diting/js/global_surface.js:",
      "throw=%d ok=%d method=%d obj-data=%d obj-getter=%d bool=%d undef=%d et-chain=%d et-alias=%d et-single=%d" % (
          len(groups["throw"]), len(groups["ok"]), len(groups["method"]),
          len(data_objs), len(acc_objs), len(groups["boolean"]), len(groups["undefined"]),
          len(et_chain), len(et_alias), len(et_single)))
print("on* set for bootstrap swap:", len(on_all))
json.dump(on_all, open(os.path.join(CHROME, "chrome-window-on-set.json") if OUT.endswith(os.path.join("crates","diting","js")) else os.devnull, "w"))
