#!/usr/bin/env python3
"""Generate crates/diting/js/sym_fix.js: Symbol-keyed prototype members from the shape audit.

  gen_sym_fix.py <engine.json> [out.js]

For every interface whose well-known-symbol members differ: remove symbols Chrome does not have (the engine put a
toStringTag on JS builtins such as Error/BigInt64Array), add the missing ones (Symbol.iterator on indexed collections =
Array.prototype.values, maplike entries/values aliases, Symbol.unscopables objects, toStringTag strings, asyncIterator),
and re-create them in Chrome's order. Runs after stub_members.js so aliases to stub members resolve.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(HERE, '../chrome/shape-audit-truth-145.json')))
E = json.load(open(sys.argv[1]))
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '../../../crates/diting/js/sym_fix.js')
D = {}
for n, t in T.items():
    e = E.get(n, {'syms': []})
    if t['syms'] == e['syms']: continue
    rm = [s for s in e['syms'] if s not in t['syms']]
    add = []
    for s in t['syms']:
        if s in e['syms']: continue
        d = t['symdesc'][s]
        add.append([s, d['k'], d.get('ref') or d.get('v') or d.get('keys') or '', d['f']])
    D[n] = {'rm': rm, 'add': add, 'order': t['syms']}
body = '// GENERATED by tools/webplatform/gen/gen_sym_fix.py from chrome/shape-audit-truth-145.json - do not edit.\n'
body += '// Symbol-keyed prototype members (iterators, toStringTag, unscopables) per the whole-surface shape audit.\n(function () {\n'
body += '  const DATA = %s;\n' % json.dumps(D, separators=(',', ':'), ensure_ascii=False)
body += '''  const wk = (s) => Symbol[s.slice(7, -1).replace('Symbol.', '')];
  const flg = (fl, data) => { const d = { enumerable: fl[0] === 'e', configurable: fl[1] === 'c' }; if (data) d.writable = fl[2] === 'w'; return d; };
  for (const n of Object.keys(DATA)) {
    const C = globalThis[n];
    if (typeof C !== 'function' || !C.prototype) continue;
    const P = C.prototype, spec = DATA[n];
    try {
      for (const s of spec.rm) { const k = wk(s); if (k) { const d = Object.getOwnPropertyDescriptor(P, k); if (d && d.configurable) delete P[k]; } }
      for (const [s, kind, x, fl] of spec.add) {
        const k = wk(s);
        if (!k || Object.prototype.hasOwnProperty.call(P, k)) continue;
        let v;
        if (kind === 'str') v = x;
        else if (kind === 'fn') v = x === 'Array.values' ? Array.prototype.values : P[x];
        else if (kind === 'obj') { v = Object.create(null); for (const key of x) v[key] = true; }
        if (v === undefined) continue;
        Object.defineProperty(P, k, Object.assign({ value: v }, flg(fl, true)));
      }
      // Chrome's relative order of the symbols that exist on both sides
      const have = spec.order.map(wk).filter((k) => k && Object.prototype.hasOwnProperty.call(P, k));
      const cur = Object.getOwnPropertySymbols(P).filter((k) => have.indexOf(k) >= 0);
      if (have.some((k, i) => k !== cur[i])) {
        for (const k of have) { const d = Object.getOwnPropertyDescriptor(P, k); if (d.configurable) { delete P[k]; Object.defineProperty(P, k, d); } }
      }
    } catch (e) {}
  }
})();
'''
open(out, 'w').write(body)
print('ifaces', len(D))
