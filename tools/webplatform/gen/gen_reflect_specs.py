#!/usr/bin/env python3
"""Extract the measured reflection specs out of gen/htmlreflect.gen.js into
the Rust static table the native reflection engine serves. The input file is
itself generated + freshness-gated from chrome/htmlreflect-truth-157.json,
so this table cannot drift semantically from the JS generator: both consume
the same measured truth. Re-run after gen_iface.py when truth is re-measured.

  python3 tools/webplatform/gen/gen_reflect_specs.py
"""
import re, json

SRC = 'crates/diting_js/js/platform/gen/htmlreflect.gen.js'
import sys
OUT = sys.argv[1] if len(sys.argv) > 1 else 'crates/diting_runtime/src/native/reflect_table.rs'

KINDS = {
    'string': 'String', 'string-nte': 'StringNte',
    'boolean-presence': 'BoolPresence', 'boolean-truefalse': 'BoolTrueFalse',
    'enum': 'Enum', 'string-known': 'Enum', 'known-fallback': 'Enum',
    'unsigned-long': 'UnsignedLong', 'unsigned-long-dim': 'UnsignedLongDim',
    'ulong-def': 'UlongDef', 'long': 'Long',
    'crossorigin': 'Crossorigin', 'url': 'Url',
}

def rs(v):
    """Rust string literal: json escaping is Rust-compatible for these."""
    return json.dumps(v, ensure_ascii=True)

def main():
    src = open(SRC).read()
    rows = re.findall(r"P\.reflector\((P_\w+), '(\w+)', (\{[^;]*?\})\);", src)
    out = [
        "//! GENERATED by tools/webplatform/gen/gen_reflect_specs.py from",
        "//! gen/htmlreflect.gen.js (itself generated from the measured",
        "//! chrome/htmlreflect-truth-157.json) - do not edit. Re-run the",
        "//! generator when the truth is re-measured.",
        "",
        "use super::reflect::{Kind, Spec};",
        "",
        "#[rustfmt::skip]",
        "pub(crate) static SPECS: &[Spec] = &[",
    ]
    count = 0
    for _proto, member, spec_json in rows:
        s = json.loads(spec_json)
        kind = s['kind']
        enum_map = s.get('map') or {}
        # legacy spellings fold into the measured enum shape (core.js mirror):
        # string-known = identity map over `known`; known-fallback invalid -> fallback
        if kind in ('string-known', 'known-fallback') and not enum_map:
            enum_map = {k: k for k in s.get('known', [])}
        # string fields only carry meaning for the enum family and plain
        # strings; numeric-default kinds (ulong-def) ride udefault instead
        def sstr(v):
            return v if isinstance(v, str) else ''
        if kind in ('enum', 'string-known', 'known-fallback'):
            invalid = sstr(s.get('invalid', s.get('fallback', s.get('default', ''))))
            missing = sstr(s.get('missing', s.get('default', '')))
        elif kind in ('string', 'string-nte'):
            invalid = ''
            missing = sstr(s.get('default', ''))
        else:
            invalid = ''
            missing = ''
        udefault = s.get('default', 0) if kind == 'ulong-def' else 0
        map_entries = ', '.join(f'({rs(k)}, {rs(v)})' for k, v in sorted(enum_map.items()))
        empty = f'Some({rs(s["empty"])})' if 'empty' in s else 'None'
        out.append(
            '    Spec { iface: %s, member: %s, attr: %s, kind: Kind::%s, default: %s, invalid: %s, empty: %s, map: &[%s], min: %d, udefault: %s, fallback_doc: %s, null_removes: %s },'
            % (
                rs(s['iface']), rs(member), rs(s['attr']), KINDS[kind],
                rs(missing if kind in ('enum', 'string-known', 'known-fallback') else str(s.get('default', ''))),
                rs(invalid), empty, map_entries,
                s.get('min', 0), udefault,
                'true' if s.get('fallbackDoc') else 'false',
                'true' if s.get('nullRemoves') else 'false',
            )
        )
        count += 1
    out.append("];")
    out.append("")
    open(OUT, 'w').write('\n'.join(out))
    print(f"wrote {OUT}: {count} specs")

if __name__ == '__main__':
    main()
