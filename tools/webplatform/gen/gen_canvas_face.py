#!/usr/bin/env python3
# Generate crates/diting/js/canvas_face.js from Chrome blank-canvas captures.
# Source: tools/webplatform/chrome/xhs-chrome-blank-consts.json (CDP capture of real Chrome's
# toDataURL on never-drawn canvases). Regenerate after re-shooting.
import json
import os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
CHROME = os.path.join(ROOT, "tools", "webplatform", "chrome")
# usage: <this script> [OUT_DIR]   (default: crates/diting/js — the checked-in artifact)
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "crates", "diting", "js")

consts = json.load(open(os.path.join(CHROME, "xhs-chrome-blank-consts.json")))

def fmt_key(f):
    return {"png": "png", "jpeg": "jpeg", "webp": "webp"}[f]

rows = []
for dim, formats in consts.items():
    for f, url in formats.items():
        rows.append('  ["%s", "%s", %s],' % (fmt_key(f), dim, json.dumps(url)))

js = """// Canvas readout face (#300015 P3): Chrome-exact bytes for blank canvases.
// The XHS shield fingerprints `canvas.toDataURL('image/webp')` on a
// never-drawn 300x150 canvas — the ENCODER signature is the signal, not the
// pixels. This engine's encoders (hand-rolled PNG, no webp/jpeg) cannot
// byte-match Chrome in general, but a blank canvas is a CONSTANT per
// (format, width, height), so the recorded Chrome output is replayed
// verbatim. GENERATED by tools/webplatform/gen/gen_canvas_face.py from
// tools/webplatform/chrome/xhs-chrome-blank-consts.json (Chrome 155 / macOS arm64,
// CDP-captured) — regenerate, don't hand-tune.
//
// Runs after bootstrap.js (its toDataURL stays as the non-blank path and the
// content-encode fallback) and before interface_sweep.js. Coverage: blank
// canvas (no 2D context, or an all-zero buffer) whose dims are in the table.
// Anything else falls through to the previous behavior.
(function () {
'use strict';
if (typeof HTMLCanvasElement === 'undefined') return;
var MAX_SCAN = 8 * 1024 * 1024;
var TABLE = [
%s
];

var BY_FMT = { png: {}, jpeg: {}, webp: {} };
for (var i = 0; i < TABLE.length; i++) {
  BY_FMT[TABLE[i][0]][TABLE[i][1]] = TABLE[i][2];
}

function bufIsBlank(ctx) {
  try {
    var b = ctx && ctx._buf;
    if (!b) return true; // no buffer == never drawn == blank
    var n = b.length;
    if (n > MAX_SCAN) return false;
    for (var j = 0; j < n; j++) if (b[j] !== 0) return false;
    return true;
  } catch (e) { return false; }
}

function blankConst(el, type) {
  var dims = el.width + 'x' + el.height;
  var byDim = BY_FMT[type];
  if (!byDim) return null;
  return byDim[dims] || null;
}

function origType(type) {
  if (!type) return 'png';
  var t = String(type).split(';')[0].toLowerCase();
  if (t === 'image/png' || t === 'png') return 'png';
  if (t === 'image/jpeg' || t === 'image/jpg' || t === 'jpeg' || t === 'jpg') return 'jpeg';
  if (t === 'image/webp' || t === 'webp') return 'webp';
  return 'png'; // Chrome: unknown types fall back to PNG
}

var prevURL = HTMLCanvasElement.prototype.toDataURL;
HTMLCanvasElement.prototype.toDataURL = function toDataURL(type, quality) {
  try {
    var t = origType(type);
    if (bufIsBlank(this._ctx)) {
      var c = blankConst(this, t);
      if (c) return c;
    }
  } catch (e) {}
  return prevURL.apply(this, arguments);
};

var prevBlob = HTMLCanvasElement.prototype.toBlob;
HTMLCanvasElement.prototype.toBlob = function toBlob(cb, type, quality) {
  try {
    var t = origType(type);
    if (t !== null && bufIsBlank(this._ctx)) {
      var c = blankConst(this, t);
      if (c) {
        var b64 = c.slice(c.indexOf(',', c.indexOf(':')) + 1);
        var bin = atob(b64);
        var bytes = new Uint8Array(bin.length);
        for (var k = 0; k < bin.length; k++) bytes[k] = bin.charCodeAt(k);
        cb(new Blob([bytes], { type: 'image/' + t }));
        return;
      }
    }
  } catch (e) {}
  return prevBlob.apply(this, arguments);
};
})();
""" % ("\n".join(rows))

open(os.path.join(OUT, "canvas_face.js"), "w").write(js)
print("wrote crates/diting/js/canvas_face.js:", len(js), "bytes,", len(rows), "consts")
