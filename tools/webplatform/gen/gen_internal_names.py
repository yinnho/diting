#!/usr/bin/env python3
"""Generate crates/diting/js/internal_names.js: the `_x` / `__x` own-property names the engine's own scripts put on
platform-interface instances (`this._nid = ...`). The enumeration patch (bootstrap.js __diting_init) hides exactly these on
instances of platform interfaces, so a page's own `_foo` expando on `document` / `performance` stays visible (Chrome-like)
while engine helper state does not leak into Object.getOwnPropertyNames(instance)."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
JS = os.path.join(HERE, '../../../crates/diting/js')
SKIP = {'platform_bundle.js', 'shape_fix.js', 'stub_members.js', 'sym_fix.js', 'internal_names.js', 'mixin_fix.js'}
names = set()
rx = re.compile(r'\bthis\.(_[A-Za-z0-9_]+)\b')
rx2 = re.compile(r'(?:\b\w+|\])\.(_[A-Za-z][A-Za-z0-9_]*)\s*=[^=]')
for f in sorted(os.listdir(JS)):
    if not f.endswith('.js') or f in SKIP: continue
    src = open(os.path.join(JS, f), encoding='utf8').read()
    names.update(rx.findall(src)); names.update(rx2.findall(src))
    if f == 'platform_bundle.js': continue
for f in sorted(os.listdir(os.path.join(JS, 'platform'))):
    if f.endswith('.js'):
        names.update(rx.findall(open(os.path.join(JS, 'platform', f), encoding='utf8').read()))
names = sorted(n for n in names if len(n) > 1)
out = os.path.join(JS, 'internal_names.js')
open(out, 'w').write('// GENERATED by tools/webplatform/gen/gen_internal_names.py - do not edit.\n'
    '// Engine-internal own-property names hidden on platform-interface instances (see the generator header).\n'
    "Object.defineProperty(globalThis, '__diting_internal_names', { value: new Set(%s), writable: true, enumerable: false, configurable: true });\n" % __import__('json').dumps(names))
print(len(names), 'names')
