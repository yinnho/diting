#!/usr/bin/env python3
"""Generate crates/diting/js/lift_own.js: move engine-kept INSTANCE own data properties to PROTOTYPE accessors.

  gen_lift_own.py <instance-audit-engine.json> Class[,Class...] [out.js] [instance-audit-chrome.json]

Chrome's WebIDL instances carry no own properties; their members are prototype accessors. The engine's real classes assign them in
constructors (`this.readyState = 0`). Defining an accessor pair with a private slot on the prototype makes those assignments (and
every internal read) keep working unchanged while the instance loses the own keys. Trade-off accepted and documented: the accessor
has a setter (Chrome's readonly attributes have none) and page writes to a readonly attribute succeed instead of being ignored.
Only names that Chrome ALSO has on the prototype (shape-audit-truth) are lifted; `_x` helpers are handled by the enumeration patch.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(HERE, '../chrome/shape-audit-truth-145.json')))
E = json.load(open(sys.argv[1]))
classes = sys.argv[2].split(',')
out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(HERE, '../../../crates/diting/js/lift_own.js')
# optional 4th arg: the Chrome-side instance audit; names Chrome's instance ALSO owns (ImageData.data) must stay own
CI = json.load(open(sys.argv[4])) if len(sys.argv) > 4 else {}
D = {}
RO = {}
for n in classes:
    inst, t = E.get(n), T.get(n)
    if not isinstance(inst, dict) or not t: print('skip', n); continue
    chrome_own = set((CI.get(n) or {}).get('names', [])) if isinstance(CI.get(n), dict) else set()
    names = [k for k in inst['names'] if k not in chrome_own if not k.startswith('_') and k in t['order'] and k != 'constructor' and t['kinds'].get(k, '').split(':')[0] in ('ro', 'rw')]
    if names: D[n] = names
# merge with the DATA already shipped in the output (the audit sees the already-lifted state, so a rerun only lists leftovers)
if os.path.exists(out):
    import re
    prev = open(out).read()
    m = re.search(r'const DATA = (\{.*?\});\n', prev)
    if m:
        for n, ks in json.loads(m.group(1)).items():
            D[n] = ks + [k for k in D.get(n, []) if k not in ks]
    m2 = re.search(r'const RO = (\{.*?\});\n', prev)
    if m2:
        for n, ks in json.loads(m2.group(1)).items():
            RO[n] = ks + [k for k in RO.get(n, []) if k not in ks]
# 刀84: Chrome-readonly members seal getter-only (shape kind ro:ec). Their internal writes go
# through globalThis.__diting_liftSlot(obj).member = v (the shared WeakMap the getters read);
# rw members keep the get+set pair exactly as before. Split AFTER the merge so classes the
# instance audit no longer probes (their members stopped being own long ago) are sealed too.
for n in list(D):
    if not T.get(n): continue
    ro = [k for k in D[n] if k in T[n]['order'] and T[n]['kinds'].get(k, '').split(':')[0] == 'ro']
    if ro:
        RO[n] = ro
        D[n] = [k for k in D[n] if k not in ro]
    if not D[n]: del D[n]
body = '// GENERATED by tools/webplatform/gen/gen_lift_own.py - do not edit. See the generator header for the contract.\n'
body += '(function () {\n  const DATA = %s;\n' % json.dumps(D, separators=(',', ':'))
body += '  const RO = %s;\n' % json.dumps(RO, separators=(',', ':'))
body += '''  const mark = globalThis.__diting_markNative || ((f) => f);
  for (const cn of Object.keys(DATA)) {
    const C = globalThis[cn];
    if (typeof C !== 'function' || !C.prototype) continue;
    const P = C.prototype, slots = new WeakMap();
    for (const name of DATA[cn]) {
      if (Object.prototype.hasOwnProperty.call(P, name)) continue;
      try {
        const get = mark({ ['get ' + name]: function () { const s = slots.get(this); return s === undefined ? undefined : s[name]; } }['get ' + name]);
        const set = mark({ ['set ' + name]: function (v) { let s = slots.get(this); if (s === undefined) { s = Object.create(null); slots.set(this, s); } s[name] = v; } }['set ' + name]);
        Object.defineProperty(P, name, { get, set, enumerable: true, configurable: true });
      } catch (e) {}
    }
  }
  // The shared slot map and __diting_liftSlot live in bootstrap.js (platform_bundle
  // constructs sealed classes during snapshot, before this file runs).
  for (const cn of Object.keys(RO)) {
    const C = globalThis[cn];
    if (typeof C !== 'function' || !C.prototype) continue;
    const P = C.prototype;
    for (const name of RO[cn]) {
      if (Object.prototype.hasOwnProperty.call(P, name)) continue;
      try {
        const get = mark({ ['get ' + name]: function () { const s = globalThis.__diting_liftSlots.get(this); return s === undefined ? undefined : s[name]; } }['get ' + name]);
        Object.defineProperty(P, name, { get, enumerable: true, configurable: true });
      } catch (e) {}
    }
  }
})();
'''
open(out, 'w').write(body)
print({k: len(v) for k, v in D.items()})
