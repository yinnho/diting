#!/usr/bin/env python3
"""Generate crates/diting/js/stub_members.js: Chrome-shaped members for PURE-STUB interfaces.

  gen_stub_members.py <engine.json> [out.js]

A pure stub is an interface whose engine constructor is one of global_surface.js's inert stubs (registered in
__diting_stubs; real classes keep their members as own instance properties, so adding prototype accessors to them
breaks their constructors) and whose prototype carries nothing but `constructor` while Chrome's has members
(USB*, Bluetooth*, XR*, GPU*, most Audio nodes, CSS Typed OM ...). Their prototypes are rebuilt from
chrome/shape-audit-truth-145.json: accessors (ro/rw), methods (name + length + e/c/w flags), constants (with the
captured value), plus statics. Behaviour contract: on a real instance of the stub (prototype-chain match) a getter returns
undefined and a method returns undefined; on any other receiver they throw `TypeError: Illegal invocation`
(Chrome's brand check - fingerprinting scripts call descriptor getters on {} to detect fakes).
Capture the engine WITHOUT stub_members.js applied (comment it out of build.rs) when regenerating.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(HERE, '../chrome/shape-audit-truth-145.json')))
E = json.load(open(sys.argv[1]))
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '../../../crates/diting/js/stub_members.js')

def member(name, k, val):
    parts = k.split(':')
    if parts[0] in ('ro', 'rw'): return [name, 'g' if parts[0] == 'ro' else 'a', 0, parts[1]]
    if parts[0] == 'function': return [name, 'f', int(parts[1]), parts[2]]
    if name in val: return [name, 'd', val[name], parts[1]]
    return None

D = {}
for n, c in T.items():
    e = E.get(n)
    if e is None or not e.get('stub') or e['order'] != ['constructor'] or len(c['order']) <= 1: continue
    pm = [member(m, c['kinds'][m], c['vals']) for m in c['order'] if m != 'constructor' and c['kinds'].get(m) not in (None, 'err')]
    sm = [member(m, c['skinds'][m], c['svals']) for m in c['statics'] if c['skinds'].get(m) not in (None, 'err')]
    pm = [x for x in pm if x]; sm = [x for x in sm if x]
    if pm or sm: D[n] = [pm, sm]
body = '// GENERATED by tools/webplatform/gen/gen_stub_members.py from chrome/shape-audit-truth-145.json - do not edit.\n'
body += '// Chrome-shaped members for pure-stub interfaces (see the generator header for the behaviour contract).\n'
body += '// entry: [name, kind g|a|f|d, length-or-value, flags e/c/w]\n(function () {\n  const DATA = %s;\n' % json.dumps(D, separators=(',', ':'), ensure_ascii=False)
body += '''  const mark = typeof _markNative === 'function' ? _markNative : (f) => f;
  const illegal = () => { throw new TypeError('Illegal invocation'); };
  const fname = (f, n) => { try { Object.defineProperty(f, 'name', { value: n, configurable: true }); } catch (e) {} return f; };
  const flg = (fl, data) => { const d = { enumerable: fl[0] === 'e', configurable: fl[1] === 'c' }; if (data) d.writable = fl[2] === 'w'; return d; };
  const install = (obj, ents, inst) => {
    for (const [name, kind, x, fl] of ents) {
      try {
        if (Object.prototype.hasOwnProperty.call(obj, name)) continue;
        if (kind === 'd') { Object.defineProperty(obj, name, Object.assign({ value: x }, flg(fl, true))); continue; }
        if (kind === 'f') {
          const f = mark(fname(function () { if (!inst(this)) illegal(); }, name));
          Object.defineProperty(f, 'length', { value: x, configurable: true });
          Object.defineProperty(obj, name, Object.assign({ value: f }, flg(fl, true)));
          continue;
        }
        const g = mark(fname(function () { if (!inst(this)) illegal(); }, 'get ' + name));
        const d = Object.assign({ get: g, set: undefined }, flg(fl, false));
        if (kind === 'a') d.set = mark(fname(function (v) { if (!inst(this)) illegal(); }, 'set ' + name));
        Object.defineProperty(obj, name, d);
      } catch (e) {}
    }
  };
  for (const n of Object.keys(DATA)) {
    const C = globalThis[n];
    if (typeof C !== 'function' || !C.prototype) continue;
    const P = C.prototype;
    install(P, DATA[n][0], (t) => t !== null && typeof t === 'object' && t !== P && Object.prototype.isPrototypeOf.call(P, t));
    if (DATA[n][1].length) install(C, DATA[n][1], (t) => t === C);
  }
})();
'''
open(out, 'w').write(body)
print('ifaces', len(D), 'members', sum(len(v[0]) + len(v[1]) for v in D.values()), 'bytes', len(body))
