#!/usr/bin/env python3
"""Bundle platform modules into the ONE script the snapshot loads
(JS-PLATFORM-ARCH sec 3.3). Generated output is checked in and freshness-gated.

  crates/diting/js/platform/core.js          L0 prelude (defines const __platform)
  crates/diting/js/platform/**/*.js          modules, each with a `//!` manifest
  -> crates/diting/js/platform_bundle.js     core + define()s in topological order + boot()

Manifest (leading `//!` lines of a module file):
  //! module: gen/storage          unique name (path-like)
  //! layer: L2                     L1 infra | L2 platform | L3 faces
  //! exposes: Storage, ...         page-visible globals this module installs
  //! requires-load: gen/x, legacy:Event   needed while the module body RUNS
  //! requires-call: legacy:_OPS           only needed inside functions later
`legacy:Name` = a free identifier owned by a legacy script. Everything else is
another module. Rules enforced here: names resolve, no cycles, a module only
depends on the same or a LOWER layer. The free-variable / require() side of the
contract is checked by tools/webplatform/analyze (needs a JS parser).

usage: bundle.py [OUT_FILE]       (default: crates/diting/js/platform_bundle.js)
"""
import glob, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PDIR = os.path.join(ROOT, "crates", "diting", "js", "platform")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "crates", "diting", "js", "platform_bundle.js")
LAYERS = {"L1": 1, "L2": 2, "L3": 3}


def parse(path):
    src = open(path, encoding="utf8").read()
    man, body = {}, []
    lines = src.split("\n")
    i = 0
    while i < len(lines) and lines[i].startswith("//!"):
        m = re.match(r"//!\s*([a-z-]+):\s*(.*)$", lines[i])
        if m:
            man[m.group(1)] = m.group(2).strip()
        elif not re.match(r"//!\s*[A-Z]", lines[i]):   # free-text note ("GENERATED by ...") is allowed
            sys.exit("%s: bad manifest line %r" % (path, lines[i]))
        i += 1
    body = "\n".join(lines[i:])
    lst = lambda k: [x.strip() for x in man.get(k, "").split(",") if x.strip() and x.strip() != "-"]
    return {
        "path": path, "name": man.get("module"), "layer": man.get("layer"),
        "exposes": lst("exposes"), "load": lst("requires-load"), "call": lst("requires-call"),
        "body": body,
    }


mods = {}
for p in sorted(glob.glob(os.path.join(PDIR, "**", "*.js"), recursive=True)):
    if os.path.basename(p) == "core.js":
        continue
    m = parse(p)
    if not m["name"] or m["layer"] not in LAYERS:
        sys.exit("%s: manifest needs `module:` and `layer: L1|L2|L3`" % p)
    if m["name"] in mods:
        sys.exit("duplicate module %s" % m["name"])
    mods[m["name"]] = m

errors = []
for m in mods.values():
    for dep in m["load"] + m["call"]:
        if dep.startswith("legacy:"):
            continue
        if dep not in mods:
            errors.append("%s requires unknown module %s" % (m["name"], dep))
        elif LAYERS[mods[dep]["layer"]] > LAYERS[m["layer"]]:
            errors.append("%s (%s) depends UP on %s (%s)" % (m["name"], m["layer"], dep, mods[dep]["layer"]))
# a module must be loaded before anything that requires it at LOAD time, and
# call-time deps must also be present by the time the bundle is booted (all
# modules are defined before boot, but boot runs in order - so load edges
# drive the order; call edges only need existence)
order, state = [], {}
def visit(n, stack):
    if state.get(n) == 2:
        return
    if state.get(n) == 1:
        errors.append("cycle: " + " -> ".join(stack + [n]))
        return
    state[n] = 1
    for dep in sorted(mods[n]["load"]):
        if not dep.startswith("legacy:") and dep in mods:
            visit(dep, stack + [n])
    state[n] = 2
    order.append(n)
for n in sorted(mods, key=lambda x: (LAYERS[mods[x]["layer"]], x)):
    visit(n, [])
if errors:
    sys.exit("bundle: " + "\n  ".join(["manifest errors:"] + errors))

core = open(os.path.join(PDIR, "core.js"), encoding="utf8").read().rstrip("\n")
out = [
    "// GENERATED by tools/webplatform/bundle.py - do not edit.",
    "// Sources: crates/diting/js/platform/{core.js, **/*.js}. Load order below is the",
    "// topological order of `requires-load`. See docs JS-PLATFORM-ARCH sec 3.3.",
    core,
    "",
]
for n in order:
    m = mods[n]
    out.append("// ---- module %s (%s) ----" % (n, m["layer"]))
    out.append("__platform.define(%s, function (exports, require, P) {" % repr(n).replace("'", '"'))
    out.append('"use strict";')
    out.append(m["body"].strip("\n"))
    out.append("});")
    out.append("")
out.append("__platform.boot();")
out.append("")
open(OUT, "w", encoding="utf8").write("\n".join(out))
print("wrote", os.path.relpath(OUT, ROOT), "modules:", ", ".join(order))
